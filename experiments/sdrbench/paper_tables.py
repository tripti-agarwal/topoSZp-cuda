#!/usr/bin/env python3
"""LaTeX tables and numbers for the paper's evaluation section.

    python3 paper_tables.py RESULTS_DIR [--out DIR] [--bounds rel:1e-3,rel:1e-4,rel:1e-5]
                            [--time-bound rel:1e-3] [--pl-bound rel:1e-3]

Writes into DIR (default RESULTS_DIR/paper):
    datasets.tex      tabular: datasets, size, largest error
    preservation.tex  tabular: plain SZp -> TopoSZp+ per dataset and bound
    time.tex          tabular: OpenMP / CUDA / SZp throughput at --time-bound
    scaling.tex       tabular: OpenMP thread sweep
    false_cases.tex   tabular: bits / FN / FP / FT of every compressor per dataset and bound
    pl.tex            tabular: cross-check with the piecewise-linear (TTK) definition
    numbers.tex       \\resdef{key}{value} for every number quoted in the text
Copy DIR to the paper (e.g. as results/) and use

    \\newcommand{\\resdef}[2]{\\expandafter\\def\\csname res@#1\\endcsname{#2}}
    \\newcommand{\\res}[1]{\\ifcsname res@#1\\endcsname\\csname res@#1\\endcsname\\else\\textbf{??}\\fi}
    \\input{results/numbers}

in the preamble, \\input{results/<table>} inside the table environments, and
\\res{<key>} in the text. Keys are listed in numbers.tex. Missing results give
"--" in tables and "??" in the text, so the paper always compiles.
"""
import argparse, os, sys
from collections import OrderedDict
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import read_results

NAME = {'CESM-ATM-2D': 'CESM 2D', 'CESM-ATM-3D': 'CESM 3D', 'Hurricane': 'Hurricane', 'NYX': 'NYX',
        'SCALE-LETKF': 'SCALE'}
SLUG = {'CESM-ATM-2D': 'cesm2d', 'CESM-ATM-3D': 'cesm3d', 'Hurricane': 'hurricane', 'NYX': 'nyx',
        'SCALE-LETKF': 'scale'}
DOMAIN = {'CESM-ATM-2D': 'Climate', 'CESM-ATM-3D': 'Climate', 'Hurricane': 'Weather', 'NYX': 'Cosmology',
          'SCALE-LETKF': 'Weather'}
COMP = OrderedDict([('toposzp', 'TopoSZp+'), ('szp', 'SZp'), ('sz3', 'SZ3'), ('sz', 'SZ2'), ('zfp', 'ZFP'),
                    ('tthresh', 'TTHRESH')])
NA = '--'

def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None

def mean(v):
    v = [x for x in v if x is not None]
    return sum(v) / len(v) if v else None

def pct(k, o):
    k, o = f(k), f(o)
    return None if k is None or not o else 100.0 * k / o

def num(x, p=1):
    if x is None:
        return NA
    if abs(x) >= 1000 and p <= 1:
        return '{:,.0f}'.format(x).replace(',', '{,}')
    return ('%.' + str(p) + 'f') % x

def times(x, p=1):
    return NA if x is None else ('%.' + str(p) + 'f$\\times$') % x

def parse_bound(s):
    mode, eb = s.split(':')
    return mode, float(eb)

def same_bound(r, b):
    return r.get('mode') == b[0] and f(r.get('eb')) is not None and abs(f(r['eb']) - b[1]) <= 1e-12 * max(1.0, b[1])

def texbound(b, show_mode=False):
    mode, eb = b
    mant, exp = ('%.0e' % eb).split('e')
    s = '$10^{%d}$' % int(exp) if mant == '1' else '$%s{\\times}10^{%d}$' % (mant, int(exp))
    return ('abs.\\ ' if mode == 'abs' else 'rel.\\ ' if show_mode else '') + s

def bslug(b):
    return '%s%d' % (b[0], -int(('%.0e' % b[1]).split('e')[1])) if ('%.0e' % b[1]).startswith('1e') else \
        '%s%s' % (b[0], ('%.0e' % b[1]).replace('-', 'm'))

def tabular(spec, head, rows):
    return '\n'.join(['\\begin{tabular}{%s}' % spec, '\\toprule'] + head + ['\\midrule'] + rows +
                     ['\\bottomrule', '\\end{tabular}', ''])

class Numbers:
    def __init__(self):
        self.d = OrderedDict()
    def set(self, key, val):
        self.d[key] = val
    def write(self, path):
        with open(path, 'w') as fh:
            fh.write('%% generated by experiments/sdrbench/paper_tables.py; \\res{key} prints the value\n')
            for k, v in self.d.items():
                fh.write('\\resdef{%s}{%s}\n' % (k, v))

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('results')
    ap.add_argument('--out', default=None)
    ap.add_argument('--bounds', default='rel:1e-3,rel:1e-4,rel:1e-5', help='bounds of the preservation / false-case tables')
    ap.add_argument('--time-bound', default='rel:1e-3')
    ap.add_argument('--pl-bound', default='rel:1e-3')
    a = ap.parse_args()
    R = a.results
    out = a.out or os.path.join(R, 'paper')
    os.makedirs(out, exist_ok=True)
    bounds = [parse_bound(s) for s in a.bounds.split(',') if s]
    tb, plb = parse_bound(a.time_bound), parse_bound(a.pl_bound)
    show_mode = len({b[0] for b in bounds}) > 1
    N = Numbers()

    main_rows = read_results(R, 'main')
    ok = [r for r in main_rows if r['status'] == 'ok']
    seen = list(OrderedDict((r['dataset'], 1) for r in main_rows))
    datasets = [d for d in NAME if d in seen] + [d for d in seen if d not in NAME]
    by_ds = lambda rows, d: [r for r in rows if r['dataset'] == d]
    nm = lambda d: NAME.get(d, d)
    sl = lambda d: SLUG.get(d, d.lower().replace('-', ''))

    # ---------------------------------------------------------------- datasets
    rows = []
    for d in datasets:
        rs = by_ds(main_rows, d)
        fields = OrderedDict((r['field'], r) for r in rs)
        r0 = next(iter(fields.values()))
        dims = '$\\times$'.join(r0['dims'].split('x'))
        gb = len(fields) * int(r0['n']) * 4 / 1e9
        errs = [f(r['err_after']) for r in by_ds(ok, d)]
        rows.append('%s & %s & %d & %s & %s & %s \\\\' % (nm(d), DOMAIN.get(d, ''), len(fields), dims,
                                                         num(gb, 2), num(max(errs) if errs else None, 3)))
        N.set('fields-%s' % sl(d), len(fields))
        N.set('size-%s' % sl(d), num(gb, 2))
    with open(os.path.join(out, 'datasets.tex'), 'w') as fh:
        fh.write(tabular('@{}llrlrr@{}', ['\\textbf{Dataset} & \\textbf{Domain} & \\textbf{Fields} & \\textbf{Dimensions} & '
                                          '\\textbf{GB} & \\textbf{Err.\\ ($\\varepsilon$)} \\\\'], rows))

    # ---------------------------------------------------------------- run counts, error, guarantees
    skipped = [r for r in main_rows if r['status'] == 'format_limit']
    failed = [r for r in main_rows if r['status'] not in ('ok', 'format_limit')]
    N.set('runs-total', len(main_rows)); N.set('runs-ok', len(ok))
    N.set('runs-skipped', len(skipped)); N.set('runs-failed', len(failed))
    errs = [f(r['err_after']) for r in ok]
    N.set('maxerr', num(max(errs) if errs else None, 3))
    for nd in (2, 3):
        e = [f(r['err_after']) for r in ok if len(r['dims'].split('x')) == nd]
        N.set('maxerr-%dd' % nd, num(max(e) if e else None, 3))
    fpft = sum((f(r['FP_after']) or 0) + (f(r['FT_after']) or 0) for r in ok)
    N.set('fpft-total', num(fpft, 0))
    ext_after = [pct(f(r['max_kept_after']) + f(r['min_kept_after']), f(r['max_orig_after']) + f(r['min_orig_after']))
                 for r in ok if (f(r['max_orig_after']) or 0) + (f(r['min_orig_after']) or 0) > 0]
    N.set('extkept-min', num(min(ext_after) if ext_after else None, 1))
    ident = [r['cpu_gpu_identical'] for r in ok if r.get('cpu_gpu_identical') not in (None, '')]
    N.set('identical', '%d of %d' % (sum(x == '1' for x in ident), len(ident)))

    # ---------------------------------------------------------------- preservation
    ext = lambda r, s: pct(f(r['max_kept_' + s]) + f(r['min_kept_' + s]), f(r['max_orig_' + s]) + f(r['min_orig_' + s]))
    sad = lambda r, s: pct(r['sad_kept_' + s], r['sad_orig_' + s])
    allcp = lambda r, s: pct(f(r['max_kept_' + s]) + f(r['min_kept_' + s]) + f(r['sad_kept_' + s]),
                             f(r['max_orig_' + s]) + f(r['min_orig_' + s]) + f(r['sad_orig_' + s]))
    rows = []
    fnred = {b: [] for b in bounds}
    for i, d in enumerate(datasets):
        if i:
            rows.append('\\midrule')
        for j, b in enumerate(bounds):
            rs = [r for r in by_ds(main_rows, d) if same_bound(r, b)]
            g = [r for r in rs if r['status'] == 'ok']
            sk = sum(r['status'] == 'format_limit' for r in rs)
            fnb, fna = mean([f(r['FN_before']) for r in g]), mean([f(r['FN_after']) for r in g])
            red = fnb / fna if fnb is not None and fna else None
            vals = {'ext': (mean([ext(r, 'before') for r in g]), mean([ext(r, 'after') for r in g])),
                    'sad': (mean([sad(r, 'before') for r in g]), mean([sad(r, 'after') for r in g])),
                    'all': (mean([allcp(r, 'before') for r in g]), mean([allcp(r, 'after') for r in g]))}
            rt, rz = mean([f(r['toposzp_ratio']) for r in g]), mean([f(r['szp_ratio']) for r in g])
            arrow = lambda p: '%s$\\to$%s' % (num(p[0]), num(p[1]))
            rows.append(' & '.join([nm(d) if j == 0 else '', texbound(b, show_mode),
                                    '%d%s' % (len(g), '$^{*}$' if sk else ''),
                                    times(rt, 2), times(rz, 2), arrow(vals['ext']), arrow(vals['sad']),
                                    arrow(vals['all']), '%s$\\to$%s' % (num(fnb, 0), num(fna, 0)), times(red),
                                    num(sum(f(r['FP_after']) or 0 for r in g) if g else None, 0),
                                    num(sum(f(r['FT_after']) or 0 for r in g) if g else None, 0),
                                    num(max([f(r['err_after']) for r in g]) if g else None, 2)]) + ' \\\\')
            k = '%s-%s' % (sl(d), bslug(b))
            N.set('fnred-' + k, num(red, 1)); N.set('ratio-' + k, num(rt, 2)); N.set('ratioszp-' + k, num(rz, 2))
            N.set('ratiofrac-' + k, num(rt / rz if rt and rz else None, 2))
            for key, (bv, av) in vals.items():
                N.set('%sbefore-%s' % (key, k), num(bv)); N.set('%safter-%s' % (key, k), num(av))
            if red is not None:
                fnred[b].append(red)
    for b in bounds:
        N.set('fnredmin-' + bslug(b), num(min(fnred[b]) if fnred[b] else None, 1))
        N.set('fnredmax-' + bslug(b), num(max(fnred[b]) if fnred[b] else None, 1))
    with open(os.path.join(out, 'preservation.tex'), 'w') as fh:
        fh.write(tabular('@{}llrrrrrrrrrrr@{}', [
            ' & & & \\multicolumn{2}{c}{\\textbf{Ratio}} & \\multicolumn{3}{c}{\\textbf{Kept (\\%), SZp$\\to$TopoSZp+}} & '
            '\\multicolumn{2}{c}{\\textbf{FN per field}} & & & \\\\',
            '\\cmidrule(lr){4-5}\\cmidrule(lr){6-8}\\cmidrule(lr){9-10}',
            '\\textbf{Dataset} & \\textbf{Bound} & \\textbf{Fields} & \\textbf{TopoSZp+} & \\textbf{SZp} & \\textbf{Extrema} & '
            '\\textbf{Saddles} & \\textbf{All} & \\textbf{SZp$\\to$TopoSZp+} & \\textbf{Red.} & \\textbf{FP} & \\textbf{FT} & '
            '\\textbf{Max err.\\ ($\\varepsilon$)} \\\\'], rows))

    # ---------------------------------------------------------------- time (throughput)
    rows = []
    for d in datasets:
        g = [r for r in by_ds(ok, d) if same_bound(r, tb)]
        gb = sum(4.0 * f(r['n']) / 1e9 for r in g)
        def thr(key):
            t = [f(r.get(key)) for r in g]
            return None if not g or None in t or not sum(t) else gb / sum(t)
        cc, cd, gc, gd, zc, zd = (thr(k) for k in ('cpu_comp_s', 'cpu_decomp_s', 'gpu_comp_s', 'gpu_decomp_s',
                                                    'szp_comp_s', 'szp_decomp_s'))
        idn = [r['cpu_gpu_identical'] for r in g if r.get('cpu_gpu_identical') not in (None, '')]
        rows.append(' & '.join([nm(d), num(cc, 2), num(cd, 2), num(gc, 2), num(gd, 2), num(zc, 2), num(zd, 2)]) + ' \\\\')
        k = sl(d)
        for key, v in (('cpucomp', cc), ('cpudecomp', cd), ('gpucomp', gc), ('gpudecomp', gd), ('szpcomp', zc),
                       ('szpdecomp', zd)):
            N.set('gbs-%s-%s' % (key, k), num(v, 2))
        N.set('gpux-comp-' + k, num(gc / cc if gc and cc else None, 1))
        N.set('gpux-decomp-' + k, num(gd / cd if gd and cd else None, 1))
        N.set('overhead-comp-' + k, num(zc / cc if zc and cc else None, 1))       # SZp throughput / TopoSZp+ throughput
        N.set('overhead-decomp-' + k, num(zd / cd if zd and cd else None, 1))
    thr_used = ok[0]['threads'] if ok else '?'
    N.set('threads', thr_used)
    with open(os.path.join(out, 'time.tex'), 'w') as fh:
        fh.write(tabular('@{}lrrrrrr@{}', [
            ' & \\multicolumn{4}{c}{\\textbf{TopoSZp+}} & \\multicolumn{2}{c}{\\textbf{SZp}} \\\\',
            '\\cmidrule(lr){2-5}\\cmidrule(lr){6-7}',
            ' & \\multicolumn{2}{c}{\\textbf{OpenMP}} & \\multicolumn{2}{c}{\\textbf{CUDA}} & \\multicolumn{2}{c}{\\textbf{OpenMP}} \\\\',
            '\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}',
            '\\textbf{Dataset} & \\textbf{Comp.} & \\textbf{Dec.} & \\textbf{Comp.} & \\textbf{Dec.} & \\textbf{Comp.} & '
            '\\textbf{Dec.} \\\\'], rows))

    # ---------------------------------------------------------------- scaling
    sc = [r for r in read_results(R, 'scaling') if r['status'] == 'ok']
    ths = sorted({int(r['threads']) for r in sc})
    rows = []
    for d in [x for x in datasets if any(r['dataset'] == x for r in sc)]:
        g = by_ds(sc, d)
        tc = {t: mean([f(r['comp_s']) for r in g if int(r['threads']) == t]) for t in ths}
        td = {t: mean([f(r['decomp_s']) for r in g if int(r['threads']) == t]) for t in ths}
        spc = tc[ths[0]] / tc[ths[-1]] if tc.get(ths[0]) and tc.get(ths[-1]) else None
        spd = td[ths[0]] / td[ths[-1]] if td.get(ths[0]) and td.get(ths[-1]) else None
        idn = all(r.get('identical_to_first') in ('1', 'True', 'yes') for r in g)
        rows.append(' & '.join([nm(d)] + [num(tc[t], 3) for t in ths] + [times(spc), times(spd)]) + ' \\\\')
        N.set('scale-identical-' + sl(d), 'yes' if idn else 'no')
        N.set('scale-comp-' + sl(d), num(spc, 1)); N.set('scale-decomp-' + sl(d), num(spd, 1))
    N.set('scale-maxthreads', ths[-1] if ths else '??')
    with open(os.path.join(out, 'scaling.tex'), 'w') as fh:
        fh.write(tabular('@{}l' + 'r' * len(ths) + 'rr@{}', [
            ' & \\multicolumn{%d}{c}{\\textbf{Comp.\\ time (s) per thread count}} & \\multicolumn{2}{c}{\\textbf{Speedup, %d t}} \\\\'
            % (len(ths), ths[-1] if ths else 0),
            '\\cmidrule(lr){2-%d}\\cmidrule(lr){%d-%d}' % (len(ths) + 1, len(ths) + 2, len(ths) + 3),
            '\\textbf{Dataset} & ' + ' & '.join('\\textbf{%d}' % t for t in ths) + ' & \\textbf{Comp.} & \\textbf{Dec.} \\\\'],
            rows))

    # ---------------------------------------------------------------- false cases
    br = [r for r in read_results(R, 'baselines') if r['status'] == 'ok']
    comps = [c for c in COMP if any(r['compressor'] == c for r in br)]
    rows = []
    for i, d in enumerate([x for x in datasets if any(r['dataset'] == x for r in br)]):
        if i:
            rows.append('\\midrule')
        cells = OrderedDict((c, []) for c in comps)
        for b in bounds:
            g = [r for r in by_ds(br, d) if same_bound(r, b)]
            per = OrderedDict((c, [r for r in g if r['compressor'] == c]) for c in comps)
            have = [set(r['field'] for r in v) for v in per.values() if v]
            common = set.intersection(*have) if have else set()
            stat = {}
            for c in comps:
                v = [r for r in per[c] if r['field'] in common]
                stat[c] = {k: mean([f(r[k]) for r in v]) for k in ('bitrate', 'FN', 'FP', 'FT')}
                cells[c] += [num(stat[c]['bitrate'], 2), num(stat[c]['FN'], 0), num(stat[c]['FP'], 0), num(stat[c]['FT'], 0)]
            tot = lambda c: None if stat[c]['FN'] is None else stat[c]['FN'] + stat[c]['FP'] + stat[c]['FT']
            k = '%s-%s' % (sl(d), bslug(b))
            for c in comps:
                ck = '%s-%s' % (c, k)
                N.set('bits-' + ck, num(stat[c]['bitrate'], 2))
                for m in ('FN', 'FP', 'FT'):
                    N.set('%s-%s' % (m.lower(), ck), num(stat[c][m], 0))
                N.set('total-' + ck, num(tot(c), 0))
                if c == 'toposzp' or 'toposzp' not in stat:
                    continue
                if tot(c) and tot('toposzp'):
                    N.set('totalx-' + ck, num(tot(c) / tot('toposzp'), 1))
                if stat[c]['bitrate'] and stat['toposzp']['bitrate']:
                    N.set('bitsx-' + ck, num(stat['toposzp']['bitrate'] / stat[c]['bitrate'], 1))
            N.set('fields-compared-' + k, len(common))
        for j, c in enumerate(comps):
            rows.append(' & '.join([nm(d) if j == 0 else '', COMP[c]] + cells[c]) + ' \\\\')
    head = [' & ' + ''.join(' & \\multicolumn{4}{c}{\\textbf{%s}}' % texbound(b, True) for b in bounds) + ' \\\\',
            ''.join('\\cmidrule(lr){%d-%d}' % (3 + 4 * i, 6 + 4 * i) for i in range(len(bounds))),
            '\\textbf{Dataset} & \\textbf{Compressor}' + ' & \\textbf{Bits} & \\textbf{FN} & \\textbf{FP} & \\textbf{FT}' * len(bounds)
            + ' \\\\']
    with open(os.path.join(out, 'false_cases.tex'), 'w') as fh:
        fh.write(tabular('@{}ll' + 'rrrr' * len(bounds) + '@{}', head, rows))

    # ---------------------------------------------------------------- PL cross-check
    pl = [r for r in read_results(R, 'pl') if r['status'] == 'ok' and same_bound(r, plb)]
    def pc(r, k, cnt):
        v = f(r.get(k))
        return None if v is None or v < 0 or not f(r.get(cnt)) else v
    rows = []
    for d in [x for x in datasets if any(r['dataset'] == x for r in pl)]:
        g = by_ds(pl, d)
        e = mean([pc(r, 'pl_extrema_kept_final_pct', 'pl_extrema') for r in g])
        s0, s1 = mean([pc(r, 'pl_saddles_kept_raw_pct', 'pl_saddles') for r in g]), \
            mean([pc(r, 'pl_saddles_kept_final_pct', 'pl_saddles') for r in g])
        fp0, fp1 = mean([f(r['FP_raw']) for r in g]), mean([f(r['FP_final']) for r in g])
        ft0, ft1 = mean([f(r['FT_raw']) for r in g]), mean([f(r['FT_final']) for r in g])
        ax = mean([pc(r, 'axis_saddles_that_are_pl_pct', 'axis_saddles') for r in g])
        N.set('plfields-' + sl(d), len(g))
        rows.append(' & '.join([nm(d), num(e), '%s$\\to$%s' % (num(s0), num(s1)),
                                '%s$\\to$%s' % (num(fp0, 0), num(fp1, 0)), '%s$\\to$%s' % (num(ft0, 0), num(ft1, 0)),
                                num(ax)]) + ' \\\\')
        k = sl(d)
        for key, v, p in (('plext', e, 1), ('plsadszp', s0, 1), ('plsadtopo', s1, 1), ('plfpszp', fp0, 0),
                          ('plfptopo', fp1, 0), ('axispl', ax, 1)):
            N.set('%s-%s' % (key, k), num(v, p))
    with open(os.path.join(out, 'pl.tex'), 'w') as fh:
        fh.write(tabular('@{}lrrrrr@{}', [
            ' & \\textbf{Extrema} & \\textbf{Saddles} & & & \\textbf{Axis sad.} \\\\',
            '\\textbf{Dataset} & \\textbf{kept (\\%)} & \\textbf{kept (\\%)} & \\textbf{FP} & \\textbf{FT} & '
            '\\textbf{PL (\\%)} \\\\'], rows))

    # bit-rate plots made by summarize.py (needs matplotlib)
    import glob, shutil
    for src in glob.glob(os.path.join(R, 'plots', 'bitrate_*.pdf')):
        shutil.copy(src, os.path.join(out, os.path.basename(src)))

    N.write(os.path.join(out, 'numbers.tex'))
    print('wrote %s/{datasets,preservation,time,scaling,false_cases,pl,numbers}.tex (%d numbers)' % (out, len(N.d)))

if __name__ == '__main__':
    main()
